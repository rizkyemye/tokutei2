-- ===== belajar.sql =====
-- progres belajar per hari & sesi (30 hari x 3 sesi)
create table if not exists progres (
  id      bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  hari    int  not null check (hari between 1 and 30),
  sesi    text not null check (sesi in ('materi','pagi','pagi1','pagi2','pagi3','siang','malam')),
  skor    int,
  total   int,
  selesai timestamptz not null default now(),
  unique (user_id, hari, sesi)
);

alter table progres enable row level security;
drop policy if exists progres_baca on progres;
create policy progres_baca on progres for select to authenticated using (auth.uid() = user_id);
drop policy if exists progres_tulis on progres;
create policy progres_tulis on progres for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists progres_ubah on progres;
create policy progres_ubah on progres for update to authenticated using (auth.uid() = user_id);

-- ===== sesi-pagi.sql =====
-- perbaikan: constraint lama menolak baris lama (sesi 'pagi')
alter table progres drop constraint if exists progres_sesi_check;

-- baris lama 'pagi' -> jadi 'pagi1'
update progres set sesi = 'pagi1' where sesi = 'pagi';

alter table progres add constraint progres_sesi_check
  check (sesi in ('materi','pagi','pagi1','pagi2','pagi3','siang','malam'));

alter table progres add column if not exists waktu_ms int;
alter table progres add column if not exists jumlah_soal int;

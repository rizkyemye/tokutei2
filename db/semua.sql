create table if not exists materi (
  id        bigint generated by default as identity primary key,
  kategori  text not null,
  judul     text not null,
  ringkas   text,
  isi      text not null,
  urutan    int  not null default 0,
  dibuat    timestamptz not null default now()
);

create table if not exists soal (
  id         bigint generated by default as identity primary key,
  kategori   text not null,
  pertanyaan text not null,
  pilihan    jsonb not null,          -- ["a","b","c","d"]
  jawaban    int  not null,           -- index pilihan yang benar (0-3)
  penjelasan text,
  urutan     int  not null default 0
);

create table if not exists nilai (
  id      bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  skor    int  not null,
  total   int  not null,
  dibuat  timestamptz not null default now()
);

create index if not exists nilai_user_idx on nilai(user_id, dibuat desc);

-- ---------- RLS: materi & soal = baca saja untuk user login ----------
alter table materi enable row level security;
alter table soal   enable row level security;
alter table nilai  enable row level security;

drop policy if exists materi_baca on materi;
create policy materi_baca on materi for select to authenticated using (true);

drop policy if exists soal_baca on soal;
create policy soal_baca on soal for select to authenticated using (true);

drop policy if exists nilai_baca on nilai;
create policy nilai_baca on nilai for select to authenticated using (auth.uid() = user_id);

drop policy if exists nilai_tulis on nilai;
create policy nilai_tulis on nilai for insert to authenticated with check (auth.uid() = user_id);


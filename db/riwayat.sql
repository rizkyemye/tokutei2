-- riwayat jawaban (untuk sesi malam: soal hari sebelumnya ikut masuk)
create table if not exists riwayat (
  id      bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  hari    int not null,
  sesi    text not null,
  soal_id bigint,
  benar   boolean not null default false,
  dibuat  timestamptz not null default now(),
  unique (user_id, hari, sesi, soal_id)
);

alter table riwayat enable row level security;

drop policy if exists riwayat_baca on riwayat;
create policy riwayat_baca on riwayat for select to authenticated using (auth.uid() = user_id);

drop policy if exists riwayat_tulis on riwayat;
create policy riwayat_tulis on riwayat for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists riwayat_ubah on riwayat;
create policy riwayat_ubah on riwayat for update to authenticated using (auth.uid() = user_id);

-- nilai & salah (review) untuk tokutei2
create table if not exists salah (
  id      bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  soal_id bigint not null references soal(id) on delete cascade,
  dibuat  timestamptz not null default now()
);
create index if not exists salah_user_idx on salah(user_id, dibuat desc);

alter table salah enable row level security;
drop policy if exists salah_baca on salah;
drop policy if exists salah_baca on salah;
create policy salah_baca on salah for select to authenticated using (auth.uid() = user_id);
drop policy if exists salah_tulis on salah;
drop policy if exists salah_tulis on salah;
create policy salah_tulis on salah for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists salah_hapus on salah;
drop policy if exists salah_hapus on salah;
create policy salah_hapus on salah for delete to authenticated using (auth.uid() = user_id);
